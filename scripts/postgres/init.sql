-- EzMsg Initial Database Schema
-- PostgreSQL 16

-- Extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pg_trgm"; -- For text search

-- Enumerations
CREATE TYPE project_status AS ENUM ('NONE', 'ACTIVE', 'SUSPENDED', 'INACTIVE', 'DELETED');
CREATE TYPE participant_status AS ENUM ('NONE', 'ACTIVE', 'SUSPENDED', 'INACTIVE', 'COMPLETED', 'BLOCKED_SYSTEM');
CREATE TYPE messaging_channel_type AS ENUM ('NONE', 'TWILIO', 'FACEBOOK', 'MOBILE_APP', 'EMAIL');
CREATE TYPE scheduled_message_status AS ENUM ('PENDING', 'IN_PROGRESS', 'SENT', 'SKIPPED', 'FAILED', 'ABORTED');
CREATE TYPE sms_message_direction AS ENUM ('OUTGOING', 'INCOMING');
CREATE TYPE node_timing_object_type AS ENUM ('TIMING_VARIABLE', 'MESSAGING_NODE', 'MESSAGE_TEMPLATE', 'KEYWORD');
CREATE TYPE variable_type AS ENUM ('STRING', 'INTEGER', 'DECIMAL', 'DATETIME', 'BOOLEAN');
CREATE TYPE variable_source_type AS ENUM ('MANUAL', 'CALCULATED', 'EXTERNAL', 'SYSTEM');
CREATE TYPE user_role AS ENUM ('ADMIN', 'RESEARCHER', 'OPERATOR');

-- Users table
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255),
    role user_role NOT NULL DEFAULT 'OPERATOR',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    removed_at TIMESTAMPTZ
);

CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_role ON users(role);

-- Available languages
CREATE TABLE available_languages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    short_name VARCHAR(10) NOT NULL,
    code INT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    removed_at TIMESTAMPTZ
);

-- Seed languages
INSERT INTO available_languages (name, short_name, code) VALUES
